package model

// ============================================================
// 全局常量定义
// ------------------------------------------------------------
// 为什么要有这一份文件？
// 之前代码里到处写裸数字：Status: 1、Role: 1 ...
//   问题1：看不懂 —— 1 到底是"已发布"还是"待审核"？
//   问题2：写错 —— 手一抖打成 2，逻辑就错了，编译器还不报错。
// 解决办法：给每个状态起一个"有名字的常量"，代码里写
//   ArticleStatusPublished（已发布）
// 一眼看懂，且拼错常量名编译器会直接报错。
//
// 命名规则（见项目设计规范 §2）：
//   语义化前缀 + 状态名，大驼峰
//   实体(Article) + 语义(Status) + 具体值(Published)
// ============================================================

// ---------------- 角色 ----------------
// 角色体系（多用户 CMS 三级权限）
//
//	游客(0) 普通用户(1) 编辑(2) 管理员(3)
//
// 注意：0 是"未登录游客"的抽象概念，不存数据库；
//
//	users 表里 role 只存 1/2/3，默认 1（普通用户）
const (
	RoleGuest  = 0 // 游客（未登录，仅概念，不落库）
	RoleUser   = 1 // 普通用户：注册登录、投稿、评论、点赞、自建专栏
	RoleEditor = 2 // 编辑：+审核文章、管理评论
	RoleAdmin  = 3 // 管理员：全部权限（用户管理、站点设置）
)

// ---------------- 用户状态 ----------------
const (
	UserStatusDisabled = 0 // 禁用（拉黑，不能登录）
	UserStatusActive   = 1 // 正常（默认）
)

// ---------------- 专栏状态 ----------------
const (
	ColumnStatusClosed = 0 // 关闭：前台不展示
	ColumnStatusActive = 1 // 正常（默认）
)

// ---------------- 文章状态（投稿审核工作流） ----------------
// 状态机：草稿(0) → 待审核(2) → 已发布(1)
//
//	↘ 已驳回(3) → 作者修改重提 → 待审核(2)
const (
	ArticleStatusDraft     = 0 // 草稿：仅作者可见
	ArticleStatusPublished = 1 // 已发布：前台可见
	ArticleStatusPending   = 2 // 待审核：投稿后等待编辑审核
	ArticleStatusRejected  = 3 // 已驳回：原因存 RejectReason，作者可修改重提
)

// ---------------- 评论状态 ----------------
const (
	CommentStatusPending  = 0 // 待审：发表后默认，前台不展示
	CommentStatusApproved = 1 // 通过：前台展示
	CommentStatusRejected = 2 // 驳回：后台可见
)
